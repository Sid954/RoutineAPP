-- Community suggestions (run once in the Supabase SQL editor).
-- Anyone can suggest a notice; votes decide how much it is trusted. Rules live in api/_lib/suggestion-rules.js.
-- All access goes through api/suggestions.js with the service role; RLS is on with no public policies.

CREATE TABLE IF NOT EXISTS public.suggestions (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at timestamp with time zone DEFAULT timezone('utc'::text, now()) NOT NULL,
    device_id text NOT NULL,
    name text NOT NULL,
    title text NOT NULL,
    announcement text NOT NULL,
    subject text,
    type text DEFAULT 'general' NOT NULL,
    date_override date,
    subject_override text,
    semester text,
    section text,
    status text DEFAULT 'pending' NOT NULL CHECK (status IN ('pending', 'approved', 'rejected')),
    announcement_id bigint,
    dedupe_key text NOT NULL
);

CREATE INDEX IF NOT EXISTS suggestions_status_created_idx ON public.suggestions (status, created_at DESC);
CREATE INDEX IF NOT EXISTS suggestions_dedupe_idx ON public.suggestions (dedupe_key);
CREATE INDEX IF NOT EXISTS suggestions_device_idx ON public.suggestions (device_id, created_at DESC);

CREATE TABLE IF NOT EXISTS public.suggestion_votes (
    suggestion_id bigint NOT NULL REFERENCES public.suggestions(id) ON DELETE CASCADE,
    device_id text NOT NULL,
    value smallint NOT NULL CHECK (value IN (-1, 1)),
    created_at timestamp with time zone DEFAULT timezone('utc'::text, now()) NOT NULL,
    PRIMARY KEY (suggestion_id, device_id)
);

ALTER TABLE public.suggestions ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.suggestion_votes ENABLE ROW LEVEL SECURITY;

-- Marks notices that became official through community votes ("Community confirmed").
ALTER TABLE public.announcements ADD COLUMN IF NOT EXISTS source text;
